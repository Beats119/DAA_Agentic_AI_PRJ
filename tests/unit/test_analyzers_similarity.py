"""Similarity analyzer: resemblance measurement, honest language.

The analyzer must NEVER claim authorship proof or AI-generation detection.
These tests assert the disclaimer language is present and that no finding
presents resemblance as proof.
"""

import pytest

from conftest import FIXTURES_CORPUS, make_analyzer_ctx

from autograder.app.analyzers.similarity import analyzer as similarity
from autograder.app.analyzers.similarity.analyzer import (
    REVIEW_DISCLAIMER,
    jaccard,
)


def _ctx(sandbox_executor, tmp_path, source_name, **kw):
    return make_analyzer_ctx(
        sandbox_executor, tmp_path, "similarity", source_name,
        metric_params={"corpus_dir": str(FIXTURES_CORPUS)}, **kw
    )


def test_jaccard_basics():
    assert jaccard(set(), set()) == 1.0
    assert jaccard({1}, set()) == 0.0
    assert jaccard({1, 2}, {2, 3}) == pytest.approx(1 / 3)


def test_near_duplicate_flagged_for_review(sandbox_executor, tmp_path):
    ctx = _ctx(sandbox_executor, tmp_path, "correct_add.c")
    result = similarity.analyze(ctx)
    assert result.status == "completed"
    # add_variant.c is the same program with renamed identifiers.
    assert result.measurements["most_similar_file"] == "add_variant.c"
    assert result.measurements["max_similarity"] >= 0.8
    assert result.measurements["flagged_count"] >= 1
    assert any("HUMAN REVIEW" in f for f in result.findings)


def test_unrelated_code_not_flagged(sandbox_executor, tmp_path):
    ctx = _ctx(sandbox_executor, tmp_path, "unsafe.c")
    result = similarity.analyze(ctx)
    assert result.status == "completed"
    assert result.measurements["flagged_count"] == 0


def test_language_never_claims_proof(sandbox_executor, tmp_path):
    ctx = _ctx(sandbox_executor, tmp_path, "correct_add.c")
    result = similarity.analyze(ctx)
    blob = "\n".join(result.findings + result.limitations).lower()
    # The disclaimer must be present...
    assert "not proof of authorship" in blob
    # ...and no finding may present resemblance as a positive verdict.
    # (The disclaimer itself denies AI-generation detection, which is why
    # we match positive claim phrases, not bare substrings.)
    for claim in (
        "plagiarism detected",
        "is plagiarized",
        "cheating detected",
        "ai-generated code detected",
        "was generated by ai",
        "proof of plagiarism",
    ):
        assert claim not in blob, f"forbidden claim language: {claim!r}"
    # The module itself must carry the same honesty in its docstring.
    import autograder.app.analyzers.similarity.analyzer as mod

    assert "not proof of authorship" in mod.__doc__.lower()


def test_empty_corpus_is_skipped(sandbox_executor, tmp_path):
    ctx = make_analyzer_ctx(
        sandbox_executor, tmp_path, "similarity", "correct_add.c",
        metric_params={"corpus_dir": str(tmp_path / "empty")},
    )
    result = similarity.analyze(ctx)
    assert result.status == "skipped"
    assert result.score is None
